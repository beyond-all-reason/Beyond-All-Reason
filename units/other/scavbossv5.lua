local unscaledDamage = { eaterbeam = true, eaterblast = true, devourdgun = true }
local scaledProjectiles = { "shotgunarm", "gaussvolley", "gaussvolley_turbo", "gaussfinale" }

local boss = units.scavbossv5
local difficultyScale = DIFFICULTY_STEP ^ level
local statScale = playerCountScale * difficultyScale
boss.health = math.floor(boss.health * statScale + 0.5)
for name, weaponDef in pairs(boss.weapondefs) do
	if weaponDef.damage and not unscaledDamage[name] then
		for armorType, damage in pairs(weaponDef.damage) do
			weaponDef.damage[armorType] = damage * statScale
		end
	end
end
for _, name in ipairs(scaledProjectiles) do
	local weaponDef = boss.weapondefs[name]
	weaponDef.projectiles = math.floor(weaponDef.projectiles * difficultyScale + 0.5)
end

