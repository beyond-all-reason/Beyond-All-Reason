---@type Builders
local Builders = VFS.Include("spec/builders/index.lua")

local function armed()
	local m = Builders.Mission.new():WithMission("cm8_ashfall"):Arm()
	local Units, Objectives = m:Includes()
	return m, Units, Objectives
end

describe("cm8_ashfall objectives", function()
	it("the board tells the story in order", function()
		local m, _, O = armed()
		assert.are.same({ O.protect.id, O.relieve.id, O.enclave.id, O.device.id, O.kill.id }, m:ObjectiveOrder())
	end)

	it("speaks to the player, not in ids", function()
		local m, _, O = armed()
		assert.are.equal("Protect your Commander", m:TitleOf(O.protect))
		assert.are.equal("Relieve the outpost", m:TitleOf(O.relieve))
		assert.are.equal("Find the Enclave", m:TitleOf(O.enclave))
		assert.are.equal("Find the Tenebrium device", m:TitleOf(O.device))
		assert.are.equal("Kill the enemy commander", m:TitleOf(O.kill))
	end)

	it("opens with the standing line revealed and the rest dark", function()
		local m, _, O = armed()
		m:Step()
		assert.is_true(m:IsRevealed(O.protect))
		assert.is_true(m:IsRevealed(O.relieve))
		assert.is_false(m:IsRevealed(O.enclave))
	end)

	it("relief means finding the outpost AND fortifying it", function()
		local m, Units, O = armed()
		m:WithUnits(0, "corllt", 4):Step()
		assert.is_false(m:IsComplete(O.relieve), "four towers at home are not a rescue")
		m:Spot(Units.hub):Step()
		assert.is_true(m:IsComplete(O.relieve))
	end)

	it("the discoveries are gated on the story", function()
		local m, Units, O = armed()
		m:Spot(Units.beacon):Step()
		assert.is_false(m:IsComplete(O.enclave), "a latched early sighting must not finish an unasked line")
		m:WithUnits(0, "corllt", 4):Spot(Units.hub):Step():Step()
		assert.is_true(m:IsComplete(O.enclave))
		assert.is_true(m:IsRevealed(O.device))
	end)

	it("what you blew up, you found", function()
		local m, Units, O = armed()
		m:WithUnits(0, "corllt", 4):Spot(Units.hub):Step()
		m:Kill(Units.beacon, 0):Step()
		assert.is_true(m:IsComplete(O.enclave))
	end)

	it("the snipe is not gated, and it is the win", function()
		local m, Units, O = armed()
		m:Kill(Units.armadaCommander, 0):Step()
		assert.is_true(m:IsComplete(O.kill))
		m:Step()
		local verdicts = m:Calls("matchflow")
		assert.are.equal("Victory", verdicts[#verdicts].method)
		assert.are.equal(0, verdicts[#verdicts].args[1])
	end)

	it("losing your own commander is the defeat", function()
		local m, Units = armed()
		m:Kill(Units.playerCommander, 1):Step()
		local verdicts = m:Calls("matchflow")
		assert.are.equal("Defeat", verdicts[#verdicts].method)
		assert.are.same({ 0 }, verdicts[#verdicts].args[1])
	end)
end)
