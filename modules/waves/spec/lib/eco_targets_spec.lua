local EcoTargets = VFS.Include("modules/waves/lib/eco_targets.lua")

describe("wave eco targets", function()
	it("values what feeds the enemy, and ignores what moves", function()
		assert.is_nil(EcoTargets.ValueOf({ canMove = true, customParams = {} }))
		assert.are.equal(1, EcoTargets.ValueOf({ canMove = false, customParams = {} }))
		assert.are.equal(201, EcoTargets.ValueOf({ canMove = false, extractsMetal = 1, customParams = {} }))
		assert.are.equal(1000, EcoTargets.ValueOf({ canMove = false, customParams = { unitgroup = "nuke" } }))
		assert.is_number(EcoTargets.ValueOf({ canMove = true, customParams = { iscommander = "1" } }))
	end)

	it("hands the director every target, and the richest bracket as high value", function()
		local tracker = EcoTargets.New()
		tracker.Add(1, { canMove = false, customParams = {} })
		tracker.Add(2, { canMove = false, extractsMetal = 1, customParams = {} })
		tracker.Add(3, { canMove = false, extractsMetal = 1, customParams = {} })
		local targets, highValue = tracker.Targets()
		assert.are.same({ 1, 2, 3 }, targets)
		assert.are.same({ 2, 3 }, highValue)
		tracker.Remove(2)
		tracker.Remove(3)
		targets, highValue = tracker.Targets()
		assert.are.same({ 1 }, targets)
		assert.are.same({ 1 }, highValue)
	end)
end)
