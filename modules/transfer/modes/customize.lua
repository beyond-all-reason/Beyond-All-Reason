local ModeDSL = require("modules/transfer/mode_dsl")
local Mode, Transfer, Construction, Take = ModeDSL.Mode, ModeDSL.Transfer, ModeDSL.Construction, ModeDSL.Take

return Mode("Customize")
	.Desc(
		"Tweak everything. Switching to Customize keeps the current mode's settings as a starting point (defaults if you start here)."
	)
	.Ranked()
	.RetainValues()
	.Allow(Transfer.Units)
	.Unlocked()
	.Stun(Transfer.Units.Resource, 0)
	.Unlocked()
	.Delay(Construction.Build, 0)
	.Unlocked()
	.Allow(Transfer.Resources)
	.Unlocked()
	.Tax(Transfer.Resources, 0)
	.Unlocked()
	.Allow(Construction.Assist)
	.Unlocked()
	.Allow(Construction.Reclaim)
	.Unlocked()
	.Allow(Construction.Resurrect)
	.Unlocked()
	.Allow(Take)
	.Unlocked()
	.Delay(Take.Resource, 30)
	.Unlocked()
	.Expose()
