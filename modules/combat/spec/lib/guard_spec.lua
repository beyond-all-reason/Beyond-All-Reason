local Guard = VFS.Include("modules/combat/lib/guard.lua")

describe("combat guard", function()
	local guard ---@type CombatGuard

	before_each(function()
		guard = Guard.New()
	end)

	describe("protection", function()
		it("protects and unprotects", function()
			guard.Protect(7)
			assert.is_true(guard.IsProtected(7))
			guard.Unprotect(7)
			assert.is_false(guard.IsProtected(7))
		end)

		it("exposes the truthy count the hot callins read directly", function()
			guard.Protect(7)
			assert.are.equal(1, guard.protected[7])
			assert.is_nil(guard.protected[8])
		end)

		it("HasProtected reflects the set for hook add/remove decisions", function()
			assert.is_false(guard.HasProtected())
			guard.Protect(7)
			guard.Protect(9)
			assert.is_true(guard.HasProtected())
			guard.Unprotect(7)
			assert.is_true(guard.HasProtected())
			guard.Unprotect(9)
			assert.is_false(guard.HasProtected())
		end)

		it("refcounts: two overlapping lifetimes need two releases", function()
			guard.Protect(7)
			guard.Protect(7)
			guard.Unprotect(7)
			assert.is_true(guard.IsProtected(7))
			guard.Unprotect(7)
			assert.is_false(guard.IsProtected(7))
		end)

		it("reports the edges the Spring-side effects hang off", function()
			assert.is_true(guard.Protect(7))
			assert.is_false(guard.Protect(7))
			assert.is_false(guard.Unprotect(7))
			assert.is_true(guard.Unprotect(7))
		end)

		it("releasing an unprotected unit is a no-op, not a negative count", function()
			assert.is_false(guard.Unprotect(7))
			assert.is_nil(guard.protected[7])
			assert.is_true(guard.Protect(7))
			assert.is_true(guard.Unprotect(7))
		end)
	end)

	describe("stun", function()
		it("records a release frame and Tick releases at it", function()
			guard.Stun(7, 100)
			assert.is_true(guard.HasStunned())
			assert.are.same({}, guard.Tick(99))
			assert.are.same({ 7 }, guard.Tick(100))
			assert.is_false(guard.HasStunned())
		end)

		it("Tick releases only what is due", function()
			guard.Stun(7, 100)
			guard.Stun(8, 200)
			local released = guard.Tick(150)
			assert.are.same({ 7 }, released)
			assert.is_true(guard.HasStunned())
			assert.are.same({ 8 }, guard.Tick(200))
		end)

		it("re-stunning overwrites the release frame", function()
			guard.Stun(7, 100)
			guard.Stun(7, 300)
			assert.are.same({}, guard.Tick(100))
			assert.are.same({ 7 }, guard.Tick(300))
		end)

		it("a released unit is not released twice", function()
			guard.Stun(7, 100)
			guard.Tick(100)
			assert.are.same({}, guard.Tick(101))
		end)
	end)

	it("UnitDestroyed clears both ledgers, whatever the protection count", function()
		guard.Protect(7)
		guard.Protect(7)
		guard.Stun(7, 100)
		guard.UnitDestroyed(7)
		assert.is_false(guard.IsProtected(7))
		assert.is_false(guard.HasStunned())
		assert.are.same({}, guard.Tick(100))
	end)
end)
