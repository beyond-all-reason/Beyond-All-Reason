local fixture = require("spec/fixtures/mex_insertion")
describe("Area Mex insertion", function()
	it("inserts a whole mex route between existing live orders", function()
		local f = fixture()
		f.queues[11] = { { id = 10, params = { 100, 0, 0 } }, { id = 10, params = { 300, 0, 0 } } }
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:flush()
		f:expect(11, { 100, 200, 240, 300 })
	end)
	it("inserts a mex route into the pregame queue without live units", function()
		local f = fixture(true)
		f.env.WG["pregame-build"].setBuildQueue({ { -10, 100, 0, 0, 0 }, { -10, 300, 0, 0, 0 } })
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:expect(nil, { 100, 200, 240, 300 })
		assert(#f.pending == 0, "pregame must not issue live orders")
	end)
end)

local function queue(f, pregame)
	if pregame then
		f.env.WG["pregame-build"].setBuildQueue({ { -10, 100, 0, 0, 0 }, { -10, 300, 0, 0, 0 } })
	else
		f.queues[11] = { { id = 10, params = { 100, 0, 0 } }, { id = 10, params = { 300, 0, 0 } } }
	end
end
for _, pregame in ipairs({ false, true }) do
	describe(pregame and "pregame area route" or "live area route", function()
		it("keeps plain Shift append and non-Shift replace", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f:area()
			f:flush()
			f:expect(11, { 100, 300, 240, 200 })
			f.shift = false
			f:area()
			f:flush()
			f:expect(11, { 200, 240 })
		end)
		it("prepends the complete route without Shift", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f.shift = false
			f:modifier()
			f:area()
			f:flush()
			f:expect(11, { 200, 240, 100, 300 })
		end)
		it("appends after releasing the insertion action", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f:modifier()
			f:modifier(nil, true)
			f:area()
			f:flush()
			f:expect(11, { 100, 300, 240, 200 })
		end)
		it("skips already queued mexes and leaves existing commands intact", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f:modifier()
			f:area()
			f:flush()
			f:area()
			f:flush()
			f:expect(11, { 100, 200, 240, 300 })
		end)
		it("skips invalid terrain without losing the rest of the route", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f.blocked = 200
			f:modifier()
			f:area()
			f:flush()
			f:expect(11, { 100, 240, 300 })
		end)
		it("keeps the queue when every placement is invalid", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f.blocked = 200
			f.shift = false
			f:area()
			f:flush()
			f:expect(11, { 100, 300 })
		end)
		it("keeps spot worth paired with commands after filtering", function()
			local f = fixture(pregame)
			f.shift = false
			f:spot(100, 100)
			f:spot(200, 1)
			f:spot(240, 100)
			f.blocked = 100
			f:area()
			f:flush()
			f:expect(11, { 240, 200 })
		end)
		it("supports ordered prepend across successive area gestures", function()
			local f = fixture(pregame)
			queue(f, pregame)
			f:spot(200)
			f:spot(240)
			f:modifier("prepend_queue")
			f:area()
			f:flush()
			f:spot(400)
			f:area()
			f:flush()
			f:expect(11, { 200, 240, 400, 100, 300 })
		end)
	end)
end

describe("resource insertion integrations", function()
	it("places each selected builder's route using its own queue", function()
		local f = fixture()
		f:select({ 11, 12 })
		queue(f, false)
		f.queues[12] = { { id = 10, params = { 500, 0, 0 } } }
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:flush()
		f:expect(11, { 100, 200, 240, 300 })
		f:expect(12, { 500, 200, 240 })
	end)
	it("inserts the routes assigned by Build Split", function()
		local f = fixture()
		f:select({ 11, 12 })
		queue(f, false)
		f.queues[12] = { { id = 10, params = { 500, 0, 0 } } }
		f:split()
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:flush()
		-- Each builder gets a different first mex, then its peer's mex as assistance.
		local a, b = f.queues[11], f.queues[12]
		assert(#a == 4 and #b == 3)
		assert(a[1].id == 10 and a[4].id == 10 and b[1].id == 10)
		assert(a[2].id == -2 and a[3].id == -2 and b[2].id == -2 and b[3].id == -2)
		assert(a[2].params[1] ~= b[2].params[1])
	end)
	it("preserves the helper's queue when inserting without Shift", function()
		local f = fixture()
		f:select({ 11, 13 })
		queue(f, false)
		f.queues[13] = { { id = 10, params = { 500, 0, 0 } } }
		f.env.WG.areamex.setAreaMexType(-2)
		f:spot(200)
		f.shift = false
		f:modifier()
		f:area()
		f:flush()
		f:expect(11, { 200, 100, 300 })
		assert(#f.queues[13] == 2 and f.queues[13][1].id == 25 and f.queues[13][2].id == 10)
	end)
	it("falls back when CommandInsert is disabled", function()
		local f = fixture()
		queue(f, false)
		f:spot(200)
		f.env.WG.commandInsert = nil
		f:area()
		f:flush()
		f:expect(11, { 100, 300, 200 })
	end)
	it("exposes the pregame area command without a selected live builder", function()
		local f = fixture(true)
		local w, e = f:load("cmd_area_mex")
		w:CommandsChanged()
		assert(#e.widgetHandler.customCommands == 1)
		assert(f.env.WG.areamex.activatePregame(2))
		assert(f.active == f.env.GameCMD.AREA_MEX)
		assert(f.widgets.gui_pregame_build:MousePress(0, 0, 3) == false)
	end)
	it("uses the current start faction, including while Area Mex is active", function()
		local f = fixture(true)
		queue(f, true)
		f:spot(200)
		f.env.WG.areamex.setAreaMexType(-2)
		f.startDef = 3
		f:modifier()
		f:area()
		assert(f.env.WG["pregame-build"].getBuildQueue()[2][1] == 4)
	end)
	it("rejects pregame overlaps, spawn obstruction, and invalid start units", function()
		local f = fixture(true)
		f.env.WG["pregame-build"].setBuildQueue({ { 2, 200, 0, 0, 0 } })
		f:spot(200)
		f:spot(0)
		f:modifier()
		f:area()
		f:expect(nil, { 200 })
		f.startDef = 999
		f:spot(400)
		f:area()
		f:expect(nil, { 200 })
	end)
	it("allows planning before a spawn position is chosen", function()
		local f = fixture(true)
		queue(f, true)
		f.start = { -100, 0, -100 }
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:expect(nil, { 100, 300, 200, 240 })
	end)
end)

describe("insertion boundaries", function()
	it("keeps successive unacknowledged prepend batches in order", function()
		local f = fixture()
		f:modifier("prepend_queue")
		local api = f.env.WG.commandInsert
		api.InsertCommands({ 11 }, { { -2, { 200, 0, 0, 0 } }, { -2, { 240, 0, 0, 0 } } }, { shift = true })
		api.InsertCommands({ 11 }, { { -2, { 400, 0, 0, 0 } } }, { shift = true })
		f:flush()
		f:expect(11, { 200, 240, 400 })
	end)
	it("retains command flags and consumes Meta only as insertion control", function()
		local f = fixture()
		f:modifier()
		f.env.WG.commandInsert.InsertCommands(
			{ 11 },
			{ { -2, { 200, 0, 0, 3 } } },
			{ shift = true, ctrl = true, alt = true, right = true, meta = true }
		)
		local p = f.pending[1].params
		assert(p[2] == -2 and p[3] == 240 and p[7] == 3)
	end)
	it("skips non-positional and vanished targets while preserving queue indices", function()
		local f = fixture()
		f:modifier()
		f.env.Spring.GetFeaturePosition = function()
			return nil
		end
		f.queues[11] = {
			{ id = 0, params = {} },
			{ id = 10, params = { 100, 0, 0 } },
			{ id = 25, params = { 32000 } },
			{
				id = 10,
				params = { 300, 0, 0 },
			},
		}
		f.env.WG.commandInsert.InsertCommands({ 11 }, { { -2, { 200, 0, 0, 0 } } }, { shift = true })
		assert(f.pending[1].params[1] == 3)
	end)
	it("appends beyond the bounded queue scan instead of inserting at the scan limit", function()
		local f = fixture()
		f:modifier()
		for i = 1, 110 do
			f.queues[11][i] = { id = 10, params = { i, 0, 0 } }
		end
		f.env.WG.commandInsert.InsertCommands({ 11 }, { { -2, { 200, 0, 0, 0 } } }, { shift = true })
		assert(f.pending[1].params[1] == 110)
	end)
	it("cancels the active pregame area tool when selecting a blueprint", function()
		local f = fixture(true)
		assert(f.env.WG.areamex.activatePregame(2))
		f.env.WG["pregame-build"].setPreGamestartDefID(2)
		assert(f.active == 0 and f.env.WG["pregame-build"].getPreGameDefID() == 2)
	end)
	it("keeps the area route intact with empty live queues", function()
		local f = fixture()
		f:spot(200)
		f:spot(240)
		f:modifier()
		f:area()
		f:flush()
		f:expect(11, { 200, 240 })
	end)
end)

