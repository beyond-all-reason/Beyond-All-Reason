local function text(key, values)
	local s = STRINGS[key]
	if not s then
		return tostring(key)
	end
	if not values then
		return s
	end
	return (
		s:gsub("%%{(%w+)}", function(name)
			local v = values[name]
			return v ~= nil and tostring(v) or ""
		end)
	)
end

return {
	strings = STRINGS,
	text = text,
}
